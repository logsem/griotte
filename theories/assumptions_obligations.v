(** * The audited statements

    The fundamental theorem, [virtualise] (stated against the entry specs
    of the context-switch thread, [ctx_switch_entry_specs], a premise), the
    entry specs of the switcher's context-switch thread
    ([ctx_switch_entry_specs_hold]), under premises on the initial state
    and two hypotheses (the validity of the scheduler's entry and the
    safety of the context-switch thread's trap vector), and their
    composition ([virtualise_switcher]), the composition with the trap
    vector proved and the scheduler's entry reduced to the validity of its
    code capability and globals in one world ([virtualise_scheduler]), and
    per case study: the assumptions of the obligations of its trusted code
    ([<cs>_fw_obligations], at the level of the safe run of each thread)
    and its initial-state predicate. The end-to-end theorems
    ([<cs>_adequacy], [firmware_adequacy_closed]) are printed by
    [assumptions.v]; only the demo images ([<cs>_concrete]) are excluded
    from the build ([theories/dune]).

    The initial-state predicate is what the end-to-end theorem assumes of
    the initial state. [Print <cs>_initial_state_ok] is the reference; the
    annotated form [<cs>_initial_state_ok_annot], printed after it, states
    the same conditions with headings and comments as reading aids. The files
    [theories/case_studies/<dir>/<cs>_initial_state_predicate.txt] are its
    prints, generated by [dune build] (rules in [tools/prints/dune]); do not edit
    them by hand.

    Uncomment the following to print them. *)

