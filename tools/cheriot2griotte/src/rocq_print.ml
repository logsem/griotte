(* The Rocq printer: a lowered file (Lower.t) as a Rocq file in the shape
   of the hand-written case studies (theories/case_studies/cmdc/cmdc.v):
   the code as [list (list asm_code)], its assembly and [asm_check], the
   code words by block, the globals, and what the firmware needs from the
   exports.

   Each Griotte instruction or macro has above it the CHERIoT
   instruction(s) it comes from, as a comment, and [deviation] comments
   where the translation is not one-to-one (as switcher/code/switcher.v). *)

open Lower
module G = Griotte_asm

let buf = Buffer.create 4096
let p fmt = Printf.bprintf buf fmt

(* Rocq comments: [(*] and [*)] cannot occur in the CHERIoT text, but a
   double quote must be balanced; the tool never prints one in a comment. *)
let comment ind s =
  if String.contains s '"' then invalid_arg "comment with a double quote";
  p "%s(* %s *)\n" ind s

(* One segment of a block: a list literal or a macro call. *)
type seg = List of (string list * string) list (* comments, element *) | Macro of string list * string

let segments (b : block) ~(head : (string list * string) list) ~(tail : (string list * string) list) =
  let segs = ref [] and cur = ref (head @ List.map (fun l -> ([], "#" ^ G.str l)) b.labels) in
  let flush () = if !cur <> [] then segs := List !cur :: !segs; cur := [] in
  List.iter
    (fun (lw : lowered) ->
      let cms = List.map (fun s -> s) lw.prov @ List.map (fun d -> "[deviation] " ^ d) lw.devs in
      let first = ref true in
      List.iter
        (fun o ->
          let cms' = if !first then cms else [] in
          first := false;
          match o with
          | C c -> cur := !cur @ [ (cms', G.string_of_code c) ]
          | M m ->
              flush ();
              segs := Macro (cms', G.string_of_macro m) :: !segs)
        lw.outs)
    b.items;
  cur := !cur @ tail;
  flush ();
  List.rev !segs

let print_block ind (segs : seg list) =
  let n = List.length segs in
  List.iteri
    (fun k s ->
      let last = k = n - 1 in
      let sep = if last then "" else " ++" in
      match s with
      | Macro (cms, m) ->
          List.iter (comment ind) cms;
          p "%s%s%s\n" ind m sep
      | List elems ->
          p "%s[\n" ind;
          let m = List.length elems in
          List.iteri
            (fun j (cms, e) ->
              List.iter (comment (ind ^ "  ")) cms;
              p "%s  %s%s\n" ind e (if j = m - 1 then "" else ";"))
            elems;
          p "%s]%s\n" ind sep)
    segs

let posture_string = function
  | Classify.Enabled -> "InterruptEnabled"
  | Classify.Disabled -> "InterruptDisabled"
  | Classify.Inherit -> assert false

let import_comment (i : Classify.import) =
  match i.ikind with
  | Classify.Switcher -> "the switcher (.compartment_switcher), the first slot, reserved even when unused"
  | Library_call f -> Printf.sprintf "library call %s (%s)" (Demangle.demangle f) i.isym
  | Cross_call (c, f) -> Printf.sprintf "export %s.%s (%s)" c (Demangle.demangle f) i.isym
  | Shared_object (n, perms) ->
      Printf.sprintf "shared object %s, permissions %s (__import_cheriot_shared_object_%s_%s)" n perms n perms

let print ~name ~source ~sha256 ~description (l : Lower.t) =
  Buffer.clear buf;
  (match sha256 with
   | Some h -> p "(* Generated by tools/cheriot2griotte from %s\n   (sha256 %s). Do not edit. *)\n" source h
   | None -> p "(* Generated by tools/cheriot2griotte from %s. Do not edit. *)\n" source);
  let uses_setbounds =
    List.exists
      (fun fo ->
        List.exists
          (fun b -> List.exists (fun lw -> List.exists (function M (G.Setbounds _) -> true | _ -> false) lw.outs) b.items)
          fo.fo_blocks)
      l.funcs
  in
  p "From griotte Require Import machine_parameters assembler fetch%s.\n\n" (if uses_setbounds then " setbounds" else "");
  p "(** %s\n\n" description;
  (* Layout summary. *)
  let nimp = List.length l.imports in
  if nimp = 0 then p "    Imports: none.\n"
  else p "    Imports: a data prefix of %d word(s) before the code, in this order:\n" nimp;
  List.iter (fun (i, sym) -> p "    - [%s]: %s\n" sym (import_comment i)) l.imports;
  if l.gslots = [] then p "    Globals: none.\n"
  else (
    p "    Globals (from [cgp], one word per 4-byte integer):\n";
    List.iter
      (fun g ->
        p "    - [%s]: word %d, %d word(s)%s\n" g.gl.Classify.gname g.gword g.gwords
          (if g.gcap then " (a capability, initially null)" else ""))
      l.gslots);
  List.iter
    (fun fo ->
      let fr = fo.fo_frame in
      if fr.fbytes = 0 then p "    Function [%s]: no stack frame.\n" fo.fo_name
      else (
        p "    Function [%s]: a frame of %d bytes, %d word(s), one per stack slot:\n" fo.fo_name fr.fbytes
          (frame_words fr);
        List.iteri (fun k (o, sz) -> p "    - word %d: byte offset %d (%d bytes)\n" k o sz) fr.slots))
    l.funcs;
  p " *)\n\n";
  let sec = String.capitalize_ascii name in
  p "Section %s.\n" sec;
  p "  Import Asm_Griotte.\n  #[local] Open Scope Z_scope.\n  Context `{MP: MachineParameters}.\n\n";
  let blocks = List.concat_map (fun fo -> fo.fo_blocks) l.funcs in
  (* The permission pairs of the [restrict]s, as constants (as the
     hand-written temporal_isolation.v): [encodePermPair] is abstract. *)
  let perms =
    List.fold_left
      (fun acc (b : block) ->
        List.fold_left
          (fun acc (lw : lowered) ->
            List.fold_left
              (fun acc -> function
                | C (G.Instr (G.Restrict (_, _, G.E (G.Perm pp)))) when not (List.mem pp acc) -> acc @ [ pp ]
                | _ -> acc)
              acc lw.outs)
          acc b.items)
      [] blocks
  in
  G.perm_name := (fun pp -> name ^ "_" ^ Cheriot_perms.ident pp);
  List.iter
    (fun pp ->
      p "  (** The encoding of the permission and locality %s, for [restrict]. *)\n"
        (Cheriot_perms.string_of_pair pp);
      p "  Definition %s : Z := encodePermPair %s.\n\n" (!G.perm_name pp) (Cheriot_perms.string_of_pair pp))
    perms;
  p "  Definition %s_asm : list (list asm_code) :=\n" name;
  let nb = List.length blocks in
  let imp_elems =
    List.mapi
      (fun k (i, sym) -> ((if k = 0 then [ "the imports" ] else []) @ [ import_comment i ], "#@" ^ G.str sym))
      l.imports
  in
  List.iteri
    (fun k b ->
      let head = if k = 0 then imp_elems else [] in
      if k = 0 then p "    [\n" else p "    ;\n";
      print_block "      " (segments b ~head ~tail:[]))
    blocks;
  p "    ].\n\n";
  p "  Definition %s_assembled :=\n    Eval %s in assemble_block %s_asm.\n" name
    (if perms = [] then "compute" else "cbv -[encodePermPair]") name;
  p "  Lemma %s_assembles : asm_ok (assemble_block_check %s_asm).\n  Proof. asm_check. Qed.\n" name name;
  p "  Definition %s_instrs_n (n : nat) : list Word :=\n    encodeInstrsW (default [] (%s_assembled !! n)).\n\n" name name;
  p "  Definition %s_code : list Word :=\n" name;
  List.iteri (fun k _ -> p "    %s_instrs_n %d%s\n" name k (if k = nb - 1 then "." else " ++")) blocks;
  p "\n";
  let data = List.concat_map (fun g -> g.ginit_words) l.gslots in
  p "  (** The globals, in the order of their words. *)\n";
  p "  Definition %s_data : list Word := [%s].\n" name
    (String.concat "; " (List.map (fun n -> "WInt " ^ G.z n) data));
  (* Exports. *)
  List.iter
    (fun (e : export_out) ->
      let en = Demangle.demangle e.ex.efunc in
      let id = name ^ "_" ^ en in
      p "\n  (** The export [%s] ([%s], %s). *)\n" en e.ex.efunc e.ex.esym;
      if e.ex_offset = nimp then
        p "  (** Entry: word %d of the PCC region: the %d imports, then [%s]. *)\n" e.ex_offset nimp e.ex_label
      else
        p "  (** Entry: word %d of the PCC region: the %d imports, the %d word(s) of the functions\n      before it, then [%s]. *)\n"
          e.ex_offset nimp (e.ex_offset - nimp) e.ex_label;
      p "  Definition %s_offset : nat := %d.\n" id e.ex_offset;
      p "  Lemma %s_offset_label :\n    label_offset (concat %s_asm) %s = %s_offset.\n  Proof. vm_compute. reflexivity. Qed.\n" id name
        (G.str e.ex_label) id;
      p "  Definition %s_nargs : nat := %d.\n" id e.ex.enargs;
      (match e.ex.eposture with
       | Classify.Inherit -> p "  (** Posture: inherited (a library export, called through a [Sentry Inherit]). *)\n"
       | ps -> p "  Definition %s_posture : InterruptStatus := %s.\n" id (posture_string ps));
      if e.ex_frame_words > 0 then (
        p "  (** The stack frame of [%s], in words (one per stack slot). *)\n" en;
        p "  Definition %s_frame_size : nat := %d.\n" id e.ex_frame_words);
      p "  (** Minimum stack, in words: the frame (%d word(s))%s. The CHERIoT\n      export says %d (8-byte units, the frame only). *)\n"
        e.ex_frame_words
        (if e.ex_switcher_spill then "\n      and the spill of the switcher for its calls (SpillSlot_size = 4)" else "")
        e.ex.emin_stack;
      let frame = if e.ex_frame_words > 0 then id ^ "_frame_size" else "" in
      let rhs =
        match (frame, e.ex_switcher_spill) with
        | "", _ -> string_of_int e.ex_min_stack
        | f, true -> f ^ " + " ^ string_of_int (e.ex_min_stack - e.ex_frame_words)
        | f, false -> f
      in
      p "  Definition %s_min_stack : nat := %s.\n" id rhs)
    l.exports;
  (* Functions that are not exports, with a frame. *)
  List.iter
    (fun fo ->
      if fo.fo_frame.fbytes > 0
         && not (List.exists (fun (e : export_out) -> e.ex.efunc = fo.fo_func.Classify.fname) l.exports)
      then (
        p "\n  (** The stack frame of [%s], in words (one per stack slot). *)\n" fo.fo_name;
        p "  Definition %s_%s_frame_size : nat := %d.\n" name fo.fo_name (frame_words fo.fo_frame)))
    l.funcs;
  p "End %s.\n" sec;
  Buffer.contents buf
